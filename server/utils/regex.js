'use strict';

/**
 * Escapes regex metacharacters in user input to prevent RegExp injection and ReDoS attacks.
 * @param {string} str
 * @returns {string}
 */
function escapeRegex(str) {
  if (typeof str !== 'string') return '';
  return str.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

module.exports = { escapeRegex };
